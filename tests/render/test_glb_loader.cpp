// GLB loader: a valid scene loads with the expected structure; malformed inputs are rejected with a message, never a crash.
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "../common/check.hpp"

#ifndef EVG_ASSET_DIR
#define EVG_ASSET_DIR "tests/assets"
#endif

static unsigned char* read_file(const char* path, size_t* n) {
    FILE* f = fopen(path, "rb");
    if (!f) return nullptr;
    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char* buf = (unsigned char*)malloc((size_t)sz);
    *n = fread(buf, 1, (size_t)sz, f) == (size_t)sz ? (size_t)sz : 0;
    fclose(f);
    return buf;
}

int main() {
    char path[512];
    snprintf(path, sizeof path, "%s/scene.glb", EVG_ASSET_DIR);

    // valid file: structure as generated by tools/gen_assets.py
    evgx::Model* m = evg.loadglb(path);
    CHECK(m != nullptr);
    if (m) {
        CHECK(m->nprims == 5);
        CHECK(m->ninst == 6);
        CHECK(m->nmats == 7);                       // six file materials plus the default
        CHECK(m->skipped == 0);
        CHECK(m->bmax.x > m->bmin.x && m->bmax.y > m->bmin.y && m->bmax.z > m->bmin.z);
        CHECK(m->bmax.x - m->bmin.x > 6.f);        // the 7-unit ground is rotated; its world extent exceeds 6
        evg.freemodel(m);
    }

    // missing file: reported, no crash
    CHECK(evg.loadglb("/no/such/file.glb") == nullptr);
    CHECK(evg.error()[0] != 0);

    // garbage bytes: not a GLB
    const char junk[] = "this is not a glb file at all, not even close to one";
    CHECK(evg.loadglb_memory(junk, sizeof junk) == nullptr);
    CHECK(strstr(evg.error(), "GLB") != nullptr);

    // zero bytes and tiny inputs
    CHECK(evg.loadglb_memory(junk, 0) == nullptr);
    CHECK(evg.loadglb_memory(junk, 8) == nullptr);

    // truncated valid file
    size_t n = 0;
    unsigned char* buf = read_file(path, &n);
    CHECK(buf != nullptr && n > 64);
    if (buf && n > 64) {
        CHECK(evg.loadglb_memory(buf, n / 2) == nullptr);
        evgx::Model* whole = evg.loadglb_memory(buf, n);
        CHECK(whole != nullptr);
        evg.freemodel(whole);

        // wrong version number in the header
        unsigned char* bad = (unsigned char*)malloc(n);
        memcpy(bad, buf, n);
        bad[4] = 1;
        CHECK(evg.loadglb_memory(bad, n) == nullptr);
        CHECK(strstr(evg.error(), "version") != nullptr);
        free(bad);
    }
    free(buf);

    return evgtest::finish("render/glb");
}
