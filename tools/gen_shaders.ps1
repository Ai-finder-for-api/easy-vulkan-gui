# Compiles src/vulkan/shaders/*.vert|*.frag to SPIR-V with glslc and writes src/vulkan/mesh_spv.hpp.
# Run after editing a shader: powershell -ExecutionPolicy Bypass -File tools\gen_shaders.ps1
# The generated header is committed, so building evg does not need the Vulkan SDK.
$ErrorActionPreference = 'Stop'
$glslc = 'C:\VulkanSDK\1.4.350.0\Bin\glslc.exe'
$root = Split-Path -Parent $PSScriptRoot
$src = Join-Path $root 'src\vulkan\shaders'
$out = Join-Path $root 'src\vulkan\mesh_spv.hpp'

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('// Generated by tools/gen_shaders.ps1 from src/vulkan/shaders. Do not edit by hand.')
$lines.Add('#pragma once')
$lines.Add('#include <stdint.h>')
$lines.Add('namespace evgx { namespace vkp {')

foreach ($name in @('mesh.vert', 'mesh.frag')) {
    $spv = Join-Path $env:TEMP "$name.spv"
    & $glslc --target-env=vulkan1.0 -O -o $spv (Join-Path $src $name)
    if ($LASTEXITCODE -ne 0) { throw "glslc failed on $name" }
    $bytes = [System.IO.File]::ReadAllBytes($spv)
    $words = [int][math]::Floor($bytes.Length / 4)
    $ident = 'k_' + $name.Replace('.', '_')
    $lines.Add("static const uint32_t $ident[] = {")
    $row = New-Object System.Text.StringBuilder
    for ($i = 0; $i -lt $words; $i++) {
        [void]$row.Append(('0x{0:X8}u,' -f [BitConverter]::ToUInt32($bytes, 4 * $i)))
        if (($i % 8) -eq 7 -or $i -eq $words - 1) {
            $lines.Add('    ' + $row.ToString())
            [void]$row.Clear()
        }
    }
    $lines.Add('};')
    $lines.Add("static const uint32_t ${ident}_words = $words;")
}
$lines.Add('}}  // namespace evgx::vkp')
Set-Content -Path $out -Value $lines -Encoding ASCII
Write-Host "wrote $out"
